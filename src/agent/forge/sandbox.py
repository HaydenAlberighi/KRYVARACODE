"""
SandboxExecutor for KRYVARACODE Omega-Prime.
Executes synthesized code in an isolated process to prevent system corruption.

Security Model:
---------------
This sandbox provides subprocess-level isolation only. It does NOT use Docker/Podman
containers, so it provides defense-in-depth rather than hard isolation.

What it protects against:
- Accidental infinite loops (via timeout)
- Accidental memory exhaustion (via subprocess memory limits)
- Accidental file system access outside temp directory (limited by OS permissions)
- Basic code injection via argument passing (fixed via json.dumps + ast.literal_eval)

Known Limitations (subprocess-only, no container isolation):
- Malicious code can still access the file system within OS permissions
- Malicious code can still make network connections
- Malicious code can still spawn child processes
- Malicious code can still access environment variables
- No CPU/memory cgroups enforcement (reliant on OS ulimits)
- No seccomp/syscall filtering
- No namespace isolation (PID, network, mount, user)

Recommendations for production:
- Add Docker/Podman container isolation with --read-only, --cap-drop=ALL
- Use gVisor or Kata Containers for stronger kernel isolation
- Implement seccomp profiles to restrict syscalls
- Add network namespace isolation
- Use dedicated non-root user with minimal permissions
- Mount only required volumes read-only

THREAT MODEL: This sandbox assumes the SYNTHESIZED CODE is untrusted (generated by LLM).
The ARGS passed to the sandbox are also considered untrusted (user-controlled).
The WRAPPER CODE generated by _wrap_code is TRUSTED (generated by this module).
"""

